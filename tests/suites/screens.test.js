/**
 * Экраны целиком: от карточки уровня до итога.
 *
 * Здесь нажимаются настоящие кнопки настоящего приложения — иначе до
 * состояния, спрятанного внутри модуля, не добраться, а именно в нём и
 * живут ошибки: занятие, которое не кончается, кнопка, которую никто не
 * слушает, итог, засчитанный дважды.
 *
 * Правильный ответ проверка берёт не из модуля, а с экрана: находит головку
 * ноты в нарисованном SVG и переводит её высоту обратно в ноту. Это самая
 * ценная проверка тренажёра — она ловит расхождение между тем, что
 * нарисовано, и тем, что считается верным. Такое расхождение снаружи не
 * видно вообще: приложение уверенно показывает ноту и уверенно называет её
 * не тем именем.
 */

import { describe, it, equal, assert } from '../runner.js';
import { app } from '../../js/app.js';
import { actions } from '../../js/core/actions.js';
import { хранилище } from '../../js/core/store.js';
import { y } from '../../js/core/staff.js';
import { нотаПоПоложению, имя } from '../../js/core/notes.js';
import { УРОВНИ } from '../../js/core/levels.js';
import { начать } from '../../js/modules/drill.js';

const экран = () => document.getElementById('screen');

let поднято = false;

function поднять() {
    if (поднято) return;
    app.init();
    поднято = true;
}

function пауза(мс) {
    return new Promise((готово) => setTimeout(готово, мс));
}

/**
 * Ожидание перерисовки.
 *
 * Переход меняет адрес, а рисует уже обработчик hashchange — то есть не в
 * этой задаче. Без ожидания проверка смотрит на предыдущий экран и падает
 * с непонятным «кнопок нет».
 */
async function дождаться(условие, подпись, срок = 3000) {
    const край = Date.now() + срок;

    while (Date.now() < край) {
        if (условие()) return true;
        await пауза(10);
    }

    throw new Error(`Не дождались: ${подпись}`);
}

/** Все действия в разметке обязаны иметь обработчик. */
function проверитьДействия(где) {
    const { click, change } = actions.names();

    for (const el of где.querySelectorAll('[data-action]')) {
        const имя_ = el.getAttribute('data-action');
        assert(click.includes(имя_), `Некому обработать нажатие «${имя_}»`);
    }

    for (const el of где.querySelectorAll('[data-change]')) {
        const имя_ = el.getAttribute('data-change');
        assert(change.includes(имя_), `Некому обработать изменение «${имя_}»`);
    }
}

/**
 * Какая нота нарисована на экране — по высоте головки.
 *
 * Обратный перевод через ту же таблицу положений, что и рисование: если
 * сдвинется она, проверка этого не заметит, но расхождение между рисунком
 * и ответом — заметит, а оно и опасно.
 */
function нотаНаЭкране() {
    const головка = экран().querySelector('.stan-note ellipse');
    assert(головка, 'на экране нет ноты');

    const cy = Number(головка.getAttribute('cy'));

    for (let поз = -6; поз <= 14; поз += 1) {
        if (y(поз) === cy) return нотаПоПоложению(поз, 'скрипичный');
    }

    throw new Error(`Головка стоит на высоте ${cy}, которой нет на стане`);
}

function кнопкаОтвета(ступень) {
    const кнопка = [...экран().querySelectorAll('.key')].find((el) => el.dataset.note === ступень);
    assert(кнопка, `Нет кнопки «${ступень}»`);
    return кнопка;
}

describe('Выбор уровня', () => {

    it('показывает все уровни', async () => {
        хранилище.сбросить();
        хранилище.звук = false;

        поднять();
        app.go('выбор');

        await дождаться(() => экран().querySelector('.levels'), 'экран выбора');

        equal(экран().querySelectorAll('.level').length, УРОВНИ.length);
        проверитьДействия(экран());
    });

    it('у пройденного уровня закрашены звёзды', async () => {
        хранилище.записатьЗанятие('три', { верных: 10, всего: 10, звёзды: 3 });

        app.go('выбор');
        await дождаться(() => экран().querySelector('.level.done'), 'отметка пройденного уровня');

        const карточка = экран().querySelector('.level');
        equal(карточка.querySelectorAll('.star.on').length, 3);
        assert(карточка.classList.contains('done'), 'пройденный уровень не отмечен');

        хранилище.сбросить();
    });
});

describe('Занятие от начала до итога', () => {

    it('проходится нажатиями и доходит до итога', async () => {
        хранилище.сбросить();
        хранилище.звук = false;
        поднять();

        начать('три');
        await дождаться(() => экран().querySelector('.drill'), 'экран занятия');

        equal(экран().querySelectorAll('.dot').length, 10);
        equal(экран().querySelectorAll('.key').length, 3);
        проверитьДействия(экран());

        // Первый ответ — верный: он должен уйти сам, без нажатий
        кнопкаОтвета(имя(нотаНаЭкране())).click();

        await дождаться(() => экран().querySelector('.verdict.ok'), 'отметка верного ответа');
        equal(экран().querySelectorAll('.dot.ok').length, 1);

        await дождаться(() => экран().textContent.includes('2 / 10'), 'переход ко второму вопросу');

        // Остальные девять — мимо: неверный ответ ждёт нажатия «Дальше»
        for (let i = 2; i <= 10; i += 1) {
            const правильный = имя(нотаНаЭкране());
            const мимо = ['до', 'ре', 'ми'].find((с) => с !== правильный);

            кнопкаОтвета(мимо).click();

            await дождаться(() => экран().querySelector('.verdict.bad'), `ответ ${i}: отметка промаха`);

            экран().querySelector('[data-action="дальше"]').click();

            if (i < 10) await дождаться(() => экран().textContent.includes(`${i + 1} / 10`), `вопрос ${i + 1}`);
        }

        await дождаться(() => экран().querySelector('.result'), 'экран итога');

        equal(экран().querySelector('.result-score').textContent.trim(), '1 из 10');
        equal(экран().querySelectorAll('.star.on').length, 0);
        equal(экран().querySelectorAll('.miss').length, 9);
        проверитьДействия(экран());

        const пройдено = хранилище.уровень('три');
        equal(пройдено.занятий, 1);
        equal(пройдено.лучший, 1);
    });

    it('итог не засчитывается второй раз при возврате на него', async () => {
        equal(хранилище.уровень('три').занятий, 1);

        app.go('итог');
        app.render();

        await дождаться(() => экран().querySelector('.result'), 'экран итога снова');
        equal(хранилище.уровень('три').занятий, 1);
    });

    it('работа над ошибками начинает занятие из тех же нот', async () => {
        экран().querySelector('[data-action="повторить-ошибки"]').click();

        await дождаться(() => экран().querySelector('.drill'), 'занятие из ошибок');

        const сколько = экран().querySelectorAll('.dot').length;
        assert(сколько >= 4 && сколько <= 10, `вопросов в повторении: ${сколько}`);
    });

    it('выход возвращает к уровням', async () => {
        экран().querySelector('[data-action="выйти"]').click();

        await дождаться(() => экран().querySelector('.levels'), 'возврат к уровням');
        хранилище.сбросить();
    });
});

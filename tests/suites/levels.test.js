/**
 * Уровни.
 *
 * Проверяется то, что легко испортить одной правкой руками: перепутанные
 * октавы в наборе, ушедшая за три добавочные линейки нота, повторившийся
 * id — из-за него звёзды двух уровней сложились бы в один.
 */

import { describe, it, equal, assert } from '../runner.js';
import { УРОВНИ, уровень } from '../../js/core/levels.js';
import { положение, имя, нота, опора, полноеИмя } from '../../js/core/notes.js';
import { кнопки } from '../../js/core/drill.js';

describe('Уровни', () => {

    it('идут от простого к сложному', () => {
        const размеры = УРОВНИ.map((у) => у.вопросы.length);

        equal(размеры[0], 3);
        assert(размеры[размеры.length - 1] === Math.max(...размеры),
            'последний уровень не самый большой');
    });

    it('у каждого свой id, имя и непустой набор', () => {
        const виденные = new Set();

        for (const у of УРОВНИ) {
            assert(у.id && !виденные.has(у.id), `id повторяется: ${у.id}`);
            виденные.add(у.id);

            assert(у.имя && у.подпись, `у уровня ${у.id} нет подписи`);
            assert(у.вопросы.length > 0, `уровень ${у.id} пуст`);
        }
    });

    it('первый уровень — ровно до, ре и ми', () => {
        equal(уровень('три').вопросы.map((в) => имя(в.нота)), ['до', 'ре', 'ми']);
        equal(кнопки(уровень('три').вопросы).length, 3);
    });

    it('ни одна нота не уходит дальше двух добавочных линеек', () => {
        for (const у of УРОВНИ) {
            for (const в of у.вопросы) {
                const поз = положение(в.нота, в.ключ);
                assert(поз >= -4 && поз <= 12, `${у.id}: нота стоит на ${поз}`);
            }
        }
    });

    it('в уровне с двумя ключами есть оба', () => {
        const ключи = new Set(уровень('оба').вопросы.map((в) => в.ключ));
        equal([...ключи].sort(), ['басовый', 'скрипичный']);
    });

    it('до первой октавы есть и в скрипичном уровне, и в басовом', () => {
        const есть = (id, ключ) => уровень(id).вопросы
            .some((в) => в.нота === нота('до', 4) && в.ключ === ключ);

        assert(есть('стан', 'скрипичный'), 'в скрипичном нет до первой октавы');
        assert(есть('бас', 'басовый'), 'в басовом нет до первой октавы');
    });

    it('от любой ноты до опоры не больше трёх ступеней', () => {
        // Подсказка обязана быть выполнимой: «на семь ступеней выше» ребёнок
        // не отсчитает, и опоры в таком месте стоят зря
        for (const у of УРОВНИ) {
            for (const в of у.вопросы) {
                const далеко = Math.abs(опора(в.нота, в.ключ).шагов);
                assert(далеко <= 3, `${у.id}, ${полноеИмя(в.нота)}: ${далеко} ступеней до опоры`);
            }
        }
    });

    it('неизвестный уровень — это null, а не падение', () => {
        equal(уровень('нет-такого'), null);
    });
});

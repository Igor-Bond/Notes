/**
 * Движок занятия.
 *
 * Случайность здесь подменяется: занятие, которое проверяется на настоящем
 * Math.random, проверяет не логику, а везение — и падает раз в сто прогонов
 * непонятно почему.
 */

import { describe, it, equal, assert } from '../runner.js';
import { занятие, кнопки, изОшибок, звёзды, ДЛИНА } from '../../js/core/drill.js';
import { нота, имя } from '../../js/core/notes.js';

const ТРИ = [
    { нота: нота('до', 4), ключ: 'скрипичный' },
    { нота: нота('ре', 4), ключ: 'скрипичный' },
    { нота: нота('ми', 4), ключ: 'скрипичный' }
];

/** Предсказуемая «случайность»: выдаёт заданные значения по кругу. */
function по(значения) {
    let i = 0;
    return () => значения[i++ % значения.length];
}

/** Ответить верно на текущий вопрос и шагнуть дальше. */
function верно(игра) {
    игра.ответить(имя(игра.вопрос.нота));
    игра.дальше();
}

describe('Звёзды', () => {

    it('три — только без ошибок', () => {
        equal(звёзды(10, 10), 3);
        equal(звёзды(9, 10), 2);
    });

    it('две — от восьми из десяти', () => {
        equal(звёзды(8, 10), 2);
        equal(звёзды(7, 10), 1);
    });

    it('одна — от шести', () => {
        equal(звёзды(6, 10), 1);
        equal(звёзды(5, 10), 0);
    });

    it('пустое занятие звёзд не даёт', () => {
        equal(звёзды(0, 0), 0);
    });
});

describe('Занятие', () => {

    it('по умолчанию десять вопросов', () => {
        const игра = занятие(ТРИ);
        equal(игра.длина, ДЛИНА);
        equal(игра.номер, 1);
    });

    it('пустой набор — это ошибка', () => {
        let упало = false;
        try { занятие([]); } catch { упало = true; }
        assert(упало, 'занятие без вопросов собралось');
    });

    it('две одинаковые ноты подряд не выпадают', () => {
        const игра = занятие(ТРИ, { длина: 20, случайное: по([0.1, 0.15, 0.5, 0.9, 0.95, 0.4]) });

        for (let i = 1; i < игра.длина; i += 1) {
            игра.ответить(имя(игра.вопрос.нота));
            const прошлый = игра.вопрос.нота;
            игра.дальше();
            assert(игра.вопрос.нота !== прошлый, `вопрос ${i + 1} повторяет предыдущий`);
        }
    });

    it('верный ответ считается, неверный запоминается', () => {
        const игра = занятие(ТРИ, { длина: 3, случайное: по([0, 0.4, 0.8]) });

        const первый = игра.вопрос;
        equal(игра.ответить(имя(первый.нота)).верно, true);
        equal(игра.верных, 1);

        игра.дальше();

        const второй = игра.вопрос;
        const мимо = имя(второй.нота) === 'до' ? 'си' : 'до';

        equal(игра.ответить(мимо).верно, false);
        equal(игра.верных, 1);
        equal(игра.ошибки.length, 1);
        equal(игра.ошибки[0].нота, второй.нота);
        equal(игра.ошибки[0].дан, мимо);
    });

    it('второй ответ на тот же вопрос не засчитывается', () => {
        const игра = занятие(ТРИ, { длина: 2, случайное: по([0, 0.5]) });

        игра.ответить(имя(игра.вопрос.нота) === 'до' ? 'ре' : 'до');
        игра.ответить(имя(игра.вопрос.нота));

        equal(игра.верных, 0);
        equal(игра.ошибки.length, 1);
    });

    it('занятие ждёт шага и без него не двигается', () => {
        const игра = занятие(ТРИ, { длина: 3, случайное: по([0, 0.5, 0.9]) });

        equal(игра.ждётШага, false);
        игра.ответить(имя(игра.вопрос.нота));
        equal(игра.ждётШага, true);
        equal(игра.номер, 1);

        игра.дальше();
        equal(игра.номер, 2);
        equal(игра.ждётШага, false);
    });

    it('после последнего вопроса занятие закончено', () => {
        const игра = занятие(ТРИ, { длина: 3, случайное: по([0, 0.5, 0.9]) });

        верно(игра);
        верно(игра);
        equal(игра.завершено, false);
        верно(игра);

        equal(игра.завершено, true);
        equal(игра.вопрос, null);
        equal(игра.итог().верных, 3);
        equal(игра.итог().звёзды, 3);
    });

    it('история помнит каждый ответ по порядку', () => {
        const игра = занятие(ТРИ, { длина: 3, случайное: по([0, 0.5, 0.9]) });

        верно(игра);
        игра.ответить(имя(игра.вопрос.нота) === 'до' ? 'ре' : 'до');
        игра.дальше();
        верно(игра);

        equal(игра.история, [true, false, true]);
    });
});

describe('Кнопки ответа', () => {

    it('только ступени набора и в привычном порядке', () => {
        equal(кнопки(ТРИ), ['до', 'ре', 'ми']);
    });

    it('порядок не зависит от порядка набора', () => {
        equal(кнопки([...ТРИ].reverse()), ['до', 'ре', 'ми']);
    });

    it('одна и та же ступень в разных октавах — одна кнопка', () => {
        const набор = [
            { нота: нота('до', 4), ключ: 'скрипичный' },
            { нота: нота('до', 5), ключ: 'скрипичный' }
        ];

        equal(кнопки(набор), ['до']);
    });
});

describe('Работа над ошибками', () => {

    it('одна и та же нота не повторяется трижды', () => {
        const ошибки = [
            { нота: нота('фа', 4), ключ: 'скрипичный', дан: 'ми' },
            { нота: нота('фа', 4), ключ: 'скрипичный', дан: 'соль' },
            { нота: нота('ля', 4), ключ: 'скрипичный', дан: 'соль' }
        ];

        equal(изОшибок(ошибки), [
            { нота: нота('фа', 4), ключ: 'скрипичный' },
            { нота: нота('ля', 4), ключ: 'скрипичный' }
        ]);
    });

    it('одна нота в разных ключах — это разные ноты', () => {
        const ошибки = [
            { нота: нота('до', 4), ключ: 'скрипичный', дан: 'ре' },
            { нота: нота('до', 4), ключ: 'басовый', дан: 'си' }
        ];

        equal(изОшибок(ошибки).length, 2);
    });
});

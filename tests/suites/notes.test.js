/**
 * Ноты и их место на стане.
 *
 * Самый дешёвый способ сделать тренажёр вредным — ошибиться здесь: он будет
 * уверенно показывать ноту на линейке и называть её не тем именем, а
 * ребёнок будет уверенно это запоминать. Поэтому проверяются не «какие-то»
 * ноты, а именно опорные: крайние линейки обоих ключей и до первой октавы,
 * которая в скрипичном висит под станом, а в басовом над ним.
 */

import { describe, it, equal, assert } from '../runner.js';
import {
    нота, имя, октава, ступень, полноеИмя, частота,
    положение, нотаПоПоложению, добавочные, диапазон, СТУПЕНИ,
    ОПОРЫ, опора, ступенями, подсказка
} from '../../js/core/notes.js';

describe('Ноты', () => {

    it('семь ступеней в привычном порядке', () => {
        equal(СТУПЕНИ, ['до', 'ре', 'ми', 'фа', 'соль', 'ля', 'си']);
    });

    it('номер собирается из октавы и ступени', () => {
        equal(нота('до', 4), 28);
        equal(нота('си', 4), 34);
        equal(нота('до', 5), 35);
    });

    it('имя и октава разбираются обратно', () => {
        equal(имя(нота('соль', 2)), 'соль');
        equal(октава(нота('соль', 2)), 2);
        equal(ступень(нота('си', 3)), 6);
    });

    it('полное имя — по-русски, с названием октавы', () => {
        equal(полноеИмя(нота('до', 4)), 'до первой октавы');
        equal(полноеИмя(нота('соль', 2)), 'соль большой октавы');
        equal(полноеИмя(нота('ми', 3)), 'ми малой октавы');
    });

    it('ля первой октавы — 440 герц', () => {
        equal(Math.round(частота(нота('ля', 4))), 440);
    });

    it('до первой октавы — 261,6 герца', () => {
        equal(частота(нота('до', 4)).toFixed(1), '261.6');
    });

    it('октава выше — вдвое большая частота', () => {
        const низ = частота(нота('ре', 3));
        const верх = частота(нота('ре', 4));
        assert(Math.abs(верх / низ - 2) < 0.0001, `отношение ${верх / низ}`);
    });
});

describe('Место на стане', () => {

    it('нижняя линейка скрипичного — ми первой октавы', () => {
        equal(положение(нота('ми', 4), 'скрипичный'), 0);
    });

    it('верхняя линейка скрипичного — фа второй', () => {
        equal(положение(нота('фа', 5), 'скрипичный'), 8);
    });

    it('до первой октавы в скрипичном — под станом', () => {
        equal(положение(нота('до', 4), 'скрипичный'), -2);
    });

    it('нижняя линейка басового — соль большой октавы', () => {
        equal(положение(нота('соль', 2), 'басовый'), 0);
    });

    it('верхняя линейка басового — ля малой октавы', () => {
        equal(положение(нота('ля', 3), 'басовый'), 8);
    });

    it('до первой октавы в басовом — на первой добавочной сверху', () => {
        equal(положение(нота('до', 4), 'басовый'), 10);
    });

    it('обратный перевод возвращает ту же ноту', () => {
        for (const ключ of ['скрипичный', 'басовый']) {
            for (const н of диапазон(нота('до', 2), нота('до', 6))) {
                equal(нотаПоПоложению(положение(н, ключ), ключ), н);
            }
        }
    });

    it('неизвестный ключ — это ошибка, а не тихая единица', () => {
        let упало = false;
        try { положение(28, 'альтовый'); } catch { упало = true; }
        assert(упало, 'ключ «альтовый» прошёл молча');
    });
});

describe('Добавочные линейки', () => {

    it('на стане их нет', () => {
        equal(добавочные(0), []);
        equal(добавочные(4), []);
        equal(добавочные(8), []);
        equal(добавочные(-1), []);
        equal(добавочные(9), []);
    });

    it('нота на первой добавочной снизу — одна линейка', () => {
        equal(добавочные(-2), [-2]);
    });

    it('нота под первой добавочной — всё ещё одна линейка', () => {
        equal(добавочные(-3), [-2]);
    });

    it('вторая добавочная снизу — две линейки', () => {
        equal(добавочные(-4), [-2, -4]);
    });

    it('сверху — так же', () => {
        equal(добавочные(10), [10]);
        equal(добавочные(11), [10]);
        equal(добавочные(12), [10, 12]);
    });
});

describe('Опорные ноты', () => {

    it('у каждого ключа три опоры, и все они на приметных местах', () => {
        equal(ОПОРЫ.скрипичный.map((н) => положение(н, 'скрипичный')), [-2, 2, 8]);
        equal(ОПОРЫ.басовый.map((н) => положение(н, 'басовый')), [0, 6, 10]);
    });

    it('опора у самой опоры — она сама, без шагов', () => {
        equal(опора(нота('соль', 4), 'скрипичный'), { нота: нота('соль', 4), шагов: 0 });
    });

    it('берётся ближайшая, а при равенстве — нижняя', () => {
        // Ми первой октавы ровно посередине между до и соль: две ступени в
        // обе стороны. Считать снизу вверх ребёнку привычнее
        equal(опора(нота('ми', 4), 'скрипичный').нота, нота('до', 4));
        equal(опора(нота('фа', 4), 'скрипичный').нота, нота('соль', 4));
        equal(опора(нота('ми', 5), 'скрипичный').нота, нота('фа', 5));
    });

    it('знак шагов говорит, куда считать', () => {
        assert(опора(нота('ля', 4), 'скрипичный').шагов > 0, 'ля первой октавы не выше соль');
        assert(опора(нота('фа', 4), 'скрипичный').шагов < 0, 'фа первой октавы не ниже соль');
    });

    it('в басовом ключе свои опоры', () => {
        equal(опора(нота('ля', 2), 'басовый').нота, нота('соль', 2));
        equal(опора(нота('ми', 3), 'басовый').нота, нота('фа', 3));
        equal(опора(нота('си', 3), 'басовый').нота, нота('до', 4));
    });

    it('ступени склоняются', () => {
        equal(ступенями(1), 'одну ступень');
        equal(ступенями(2), 'две ступени');
        equal(ступенями(-3), 'три ступени');
        equal(ступенями(5), 'пять ступеней');
    });

    it('подсказка называет опору и сторону', () => {
        equal(подсказка(нота('ля', 4), 'скрипичный'), 'Считай от ноты соль: на одну ступень выше');
        equal(подсказка(нота('фа', 4), 'скрипичный'), 'Считай от ноты соль: на одну ступень ниже');
    });

    it('подсказка на самой опоре не заставляет считать', () => {
        equal(подсказка(нота('до', 4), 'скрипичный'), 'Это опорная нота — до первой октавы');
    });
});

/**
 * Рисунок стана.
 *
 * Проверяется не «похоже ли», а то, что поддаётся счёту: пять линеек,
 * головка ровно на своей высоте, добавочные там, где им положено, штиль в
 * нужную сторону. Разбор идёт через DOMParser, а не поиском по строке:
 * подстрока `cy="140"` нашлась бы и в соседнем элементе, а вопрос в том,
 * где стоит именно головка.
 */

import { describe, it, equal, assert } from '../runner.js';
import { нарисовать, нарисоватьКлюч, y } from '../../js/core/staff.js';
import { нота } from '../../js/core/notes.js';

function разобрать(строка) {
    const документ = new DOMParser().parseFromString(строка.trim(), 'image/svg+xml');

    const беда = документ.querySelector('parsererror');
    assert(!беда, `SVG не разобрался: ${беда?.textContent || ''}`);

    return документ.documentElement;
}

function головка(svg) {
    const эллипс = svg.querySelector('.stan-note ellipse');
    assert(эллипс, 'головка ноты не нарисована');
    return эллипс;
}

describe('Стан', () => {

    it('пять линеек', () => {
        const svg = разобрать(нарисовать({ нота: нота('ми', 4), ключ: 'скрипичный' }));
        equal(svg.querySelectorAll('.stan-lines line').length, 5);
    });

    it('ми первой октавы сидит на нижней линейке', () => {
        const svg = разобрать(нарисовать({ нота: нота('ми', 4), ключ: 'скрипичный' }));
        equal(Number(головка(svg).getAttribute('cy')), y(0));
    });

    it('фа второй октавы — на верхней', () => {
        const svg = разобрать(нарисовать({ нота: нота('фа', 5), ключ: 'скрипичный' }));
        equal(Number(головка(svg).getAttribute('cy')), y(8));
    });

    it('соль большой октавы в басовом ключе — тоже на нижней', () => {
        const svg = разобрать(нарисовать({ нота: нота('соль', 2), ключ: 'басовый' }));
        equal(Number(головка(svg).getAttribute('cy')), y(0));
    });

    it('до первой октавы получает одну добавочную линейку', () => {
        const svg = разобрать(нарисовать({ нота: нота('до', 4), ключ: 'скрипичный' }));

        const добавочные = svg.querySelectorAll('.stan-note line');
        // Одна добавочная и штиль — линий в группе ноты ровно две
        equal(добавочные.length, 2);
    });

    it('нота на стане обходится без добавочных', () => {
        const svg = разобрать(нарисовать({ нота: нота('си', 4), ключ: 'скрипичный' }));
        equal(svg.querySelectorAll('.stan-note line').length, 1);
    });

    it('штиль у нижних нот смотрит вверх, у верхних вниз', () => {
        const низ = разобрать(нарисовать({ нота: нота('ми', 4), ключ: 'скрипичный' }));
        const верх = разобрать(нарисовать({ нота: нота('ми', 5), ключ: 'скрипичный' }));

        const штиль = (svg) => svg.querySelector('.stan-note line');
        const вверх = (svg) => Number(штиль(svg).getAttribute('y2')) < Number(штиль(svg).getAttribute('y1'));

        assert(вверх(низ), 'у ми первой октавы штиль вниз');
        assert(!вверх(верх), 'у ми второй октавы штиль вверх');
    });

    it('ключи нарисованы и нарисованы по-разному', () => {
        const скрипичный = разобрать(нарисовать({ нота: нота('ми', 4), ключ: 'скрипичный' }));
        const басовый = разобрать(нарисовать({ нота: нота('соль', 2), ключ: 'басовый' }));

        const рисунок = (svg) => svg.querySelector('.stan-clef').innerHTML.trim();

        assert(рисунок(скрипичный).length > 40, 'скрипичный ключ пуст');
        assert(рисунок(басовый).length > 40, 'басовый ключ пуст');
        assert(рисунок(скрипичный) !== рисунок(басовый), 'оба ключа нарисованы одинаково');
    });

    it('подсветка ответа — класс на корне, а не другой рисунок', () => {
        const обычно = разобрать(нарисовать({ нота: нота('ми', 4), ключ: 'скрипичный' }));
        const верно = разобрать(нарисовать({ нота: нота('ми', 4), ключ: 'скрипичный', класс: 'ok' }));

        assert(верно.classList.contains('ok'), 'класс не попал на svg');
        equal(
            Number(головка(верно).getAttribute('cy')),
            Number(головка(обычно).getAttribute('cy'))
        );
    });

    it('подсказка рисует опорную ноту — подписанную и без штиля', () => {
        const svg = разобрать(нарисовать({
            нота: нота('ля', 4), ключ: 'скрипичный', опора: нота('соль', 4)
        }));

        const якорь = svg.querySelector('.stan-anchor');
        assert(якорь, 'опорная нота не нарисована');

        equal(якорь.querySelector('text').textContent, 'соль');
        equal(Number(якорь.querySelector('ellipse').getAttribute('cy')), y(2));
        equal(якорь.querySelectorAll('line').length, 0);
    });

    it('без подсказки опорной ноты нет', () => {
        const svg = разобрать(нарисовать({ нота: нота('ля', 4), ключ: 'скрипичный' }));
        equal(svg.querySelectorAll('.stan-anchor').length, 0);
    });

    it('опорная нота за станом получает свои добавочные', () => {
        const svg = разобрать(нарисовать({
            нота: нота('ми', 4), ключ: 'скрипичный', опора: нота('до', 4)
        }));

        equal(svg.querySelectorAll('.stan-anchor line').length, 1);
    });

    it('опорная нота стоит левее спрашиваемой — от неё считают', () => {
        const svg = разобрать(нарисовать({
            нота: нота('ля', 4), ключ: 'скрипичный', опора: нота('соль', 4)
        }));

        const x = (узел) => Number(узел.getAttribute('cx'));
        assert(x(svg.querySelector('.stan-anchor ellipse')) < x(головка(svg)),
            'опора нарисована правее вопроса');
    });

    it('пустой стан для карточки уровня — с ключом и без ноты', () => {
        const svg = разобрать(нарисоватьКлюч('басовый'));

        equal(svg.querySelectorAll('.stan-lines line').length, 5);
        equal(svg.querySelectorAll('ellipse').length, 0);
        assert(svg.querySelector('.stan-clef').innerHTML.trim().length > 40, 'ключ не нарисован');
    });
});

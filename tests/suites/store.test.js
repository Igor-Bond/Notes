/**
 * Хранение звёзд.
 *
 * Проверки идут по настоящему localStorage — подменять его нечем и незачем,
 * — но по другому ключу: он подставлен в tests/index.html. Без этого прогон
 * проверок стирал бы то, что ребёнок собрал на этом же устройстве.
 */

import { describe, it, equal, assert } from '../runner.js';
import { хранилище } from '../../js/core/store.js';

const КЛЮЧ = globalThis.__NOTES_KEY__;

function начисто() {
    localStorage.removeItem(КЛЮЧ);
}

describe('Хранилище', () => {

    it('проверки идут по своему ключу', () => {
        assert(КЛЮЧ && КЛЮЧ !== 'notes.v1', `ключ проверок: ${КЛЮЧ}`);
    });

    it('пустое хранилище — уровень без звёзд', () => {
        начисто();

        const у = хранилище.уровень('три');
        equal(у.занятий, 0);
        equal(у.звёзды, 0);
        equal(у.лучший, 0);
    });

    it('звук по умолчанию включён', () => {
        начисто();
        equal(хранилище.звук, true);
    });

    it('занятие запоминается', () => {
        начисто();
        хранилище.записатьЗанятие('три', { верных: 8, всего: 10, звёзды: 2 });

        const у = хранилище.уровень('три');
        equal(у.занятий, 1);
        equal(у.звёзды, 2);
        equal(у.лучший, 8);
        assert(у.когда > 0, 'время занятия не записано');
    });

    it('неудачное занятие не отнимает звёзды', () => {
        начисто();
        хранилище.записатьЗанятие('три', { верных: 10, всего: 10, звёзды: 3 });
        хранилище.записатьЗанятие('три', { верных: 4, всего: 10, звёзды: 0 });

        const у = хранилище.уровень('три');
        equal(у.занятий, 2);
        equal(у.звёзды, 3);
        equal(у.лучший, 10);
    });

    it('уровни не мешают друг другу', () => {
        начисто();
        хранилище.записатьЗанятие('три', { верных: 10, всего: 10, звёзды: 3 });

        equal(хранилище.уровень('бас').звёзды, 0);
        equal(хранилище.уровень('три').звёзды, 3);
    });

    it('звук запоминается отдельно от звёзд', () => {
        начисто();
        хранилище.звук = false;
        хранилище.записатьЗанятие('три', { верных: 10, всего: 10, звёзды: 3 });

        equal(хранилище.звук, false);
        хранилище.звук = true;
        equal(хранилище.уровень('три').звёзды, 3);
    });

    it('сброс стирает звёзды, но не настройку звука', () => {
        начисто();
        хранилище.звук = false;
        хранилище.записатьЗанятие('три', { верных: 10, всего: 10, звёзды: 3 });

        хранилище.сбросить();

        equal(хранилище.уровень('три').занятий, 0);
        equal(хранилище.звук, false);

        хранилище.звук = true;
    });

    it('испорченное содержимое читается как пустое', () => {
        localStorage.setItem(КЛЮЧ, 'это не json');
        equal(хранилище.уровень('три').занятий, 0);

        localStorage.setItem(КЛЮЧ, '{"уровни": "строка вместо списка"}');
        equal(хранилище.уровень('три').звёзды, 0);

        localStorage.setItem(КЛЮЧ, '{"уровни": {"три": {"звёзды": 99, "занятий": "много"}}}');
        equal(хранилище.уровень('три').звёзды, 3);
        equal(хранилище.уровень('три').занятий, 0);

        начисто();
    });
});

/**
 * Движок занятия: очередь вопросов, ответы, счёт.
 *
 * Без DOM и без хранилища — занятие это чистая логика, и проверять её надо
 * шагами, а не нажатиями. Отсюда же `случайное` в настройках: проверке нужна
 * предсказуемая последовательность, а приложению — обычный Math.random.
 *
 * Занятие не переходит к следующему вопросу само. Ответ только отмечается,
 * а шаг делает `дальше()` — иначе движку пришлось бы знать, сколько
 * показывать зелёную галочку, то есть знать про экран.
 */

import { СТУПЕНИ, имя } from './notes.js';

export const ДЛИНА = 10;

/**
 * Звёзды за занятие.
 *
 * Три — только без единой ошибки: «освоено» должно означать освоено, иначе
 * ребёнок собирает три звезды с семью ошибками и считает тему пройденной.
 * Две и одна — чтобы девять из десяти не выглядели провалом.
 */
export function звёзды(верных, всего) {
    if (!всего) return 0;
    if (верных === всего) return 3;
    if (верных / всего >= 0.8) return 2;
    if (верных / всего >= 0.6) return 1;
    return 0;
}

/**
 * Очередь вопросов.
 *
 * Две одинаковые ноты подряд запрещены: ребёнок отвечает второй раз не
 * читая — он помнит предыдущий ответ, и вопрос проходит мимо цели. Если в
 * наборе одна нота, запрет снимается сам собой — иначе очередь не собралась
 * бы вовсе.
 */
function очередь(набор, длина, случайное) {
    const вопросы = [];
    let прошлый = null;

    for (let i = 0; i < длина; i += 1) {
        let выбор = null;

        for (let попытка = 0; попытка < 20; попытка += 1) {
            выбор = набор[Math.floor(случайное() * набор.length)] || набор[0];

            const тот_же = прошлый && выбор.нота === прошлый.нота && выбор.ключ === прошлый.ключ;
            if (набор.length < 2 || !тот_же) break;
        }

        вопросы.push(выбор);
        прошлый = выбор;
    }

    return вопросы;
}

/**
 * Занятие по набору вопросов.
 *
 * Набор — список `{ нота, ключ }`: у уровня он свой, у работы над ошибками
 * свой. Движок про уровни не знает ничего, и благодаря этому повторение
 * ошибок не потребовало ни строчки внутри него.
 */
export function занятие(набор, { длина = ДЛИНА, случайное = Math.random } = {}) {
    if (!набор?.length) throw new Error('Набор вопросов пуст');

    const вопросы = очередь(набор, длина, случайное);
    const промахи = [];
    const история = [];   // верно ли отвечен каждый вопрос — для точек прогресса

    let номер = 0;
    let верных = 0;
    let ответ = null;      // ответ на текущий вопрос, пока не сделан шаг
    let завершено = false;

    return {
        get длина() { return вопросы.length; },
        get номер() { return номер + 1; },
        get верных() { return верных; },
        get завершено() { return завершено; },
        get ждётШага() { return ответ !== null; },
        get вопрос() { return завершено ? null : вопросы[номер]; },
        get ответ() { return ответ; },
        get ошибки() { return промахи.slice(); },
        get история() { return история.slice(); },

        /**
         * Ответ ступенью: 'до', 'ре', … Повторный ответ на тот же вопрос
         * не засчитывается — на экране в этот момент уже видно правильное,
         * и второе нажатие исправляло бы оценку по подсказке.
         */
        ответить(ступень) {
            if (завершено || ответ) return ответ;

            const вопрос = вопросы[номер];
            const верно = ступень === имя(вопрос.нота);

            if (верно) верных += 1;
            else промахи.push({ ...вопрос, дан: ступень });

            история.push(верно);

            ответ = { верно, дан: ступень, вопрос };
            return ответ;
        },

        /** Шаг вперёд. Возвращает false, когда вопросы кончились. */
        дальше() {
            if (!ответ) return !завершено;

            ответ = null;
            номер += 1;

            if (номер >= вопросы.length) завершено = true;
            return !завершено;
        },

        итог() {
            return {
                верных,
                всего: вопросы.length,
                звёзды: звёзды(верных, вопросы.length),
                ошибки: промахи.slice()
            };
        }
    };
}

/**
 * Какие кнопки показывать: только ступени, встречающиеся в наборе.
 *
 * На уровне из трёх нот семь кнопок — это семь равновероятных мишеней, и
 * ребёнок тыкает наугад. Три кнопки заставляют выбирать между тем, что он
 * правда учил.
 *
 * Порядок всегда до-ре-ми-фа-соль-ля-си: ряд, переставляющийся от уровня к
 * уровню, ломает единственную опору, которая у ребёнка уже есть.
 */
export function кнопки(набор) {
    const есть = new Set(набор.map((в) => имя(в.нота)));
    return СТУПЕНИ.filter((с) => есть.has(с));
}

/**
 * Набор для работы над ошибками — без повторов.
 *
 * Одна и та же нота, проваленная трижды, иначе заняла бы в новом занятии
 * треть вопросов, и занятие свелось бы к ней одной.
 */
export function изОшибок(ошибки) {
    const видели = new Set();

    return ошибки.filter((о) => {
        const ключ = `${о.ключ}:${о.нота}`;
        if (видели.has(ключ)) return false;
        видели.add(ключ);
        return true;
    }).map((о) => ({ нота: о.нота, ключ: о.ключ }));
}

/**
 * Уровни — от трёх нот до двух ключей сразу.
 *
 * Порядок здесь не произвольный, а порядок сольфеджио: сначала три ноты в
 * скрипичном ключе, потом пять, потом октава целиком, и только затем второй
 * ключ. Ребёнок, которому сразу показали одиннадцать нот в двух ключах, не
 * учится читать — он угадывает.
 *
 * Уровни не запираются друг за другом. Замок выглядит справедливым, но
 * ученик приходит на занятие с тем, что задали сегодня, а не с тем, до чего
 * он дошёл в игре; закрытый уровень в такой вечер означает, что тренажёр
 * бесполезен. Порядок подсказан номером и подписью — этого хватает.
 */

import { нота, диапазон } from './notes.js';

/** Ноты одного ключа подряд: набор('скрипичный', ['до', 4], ['соль', 4]). */
function набор(ключ, от, до) {
    return диапазон(нота(...от), нота(...до)).map((н) => ({ нота: н, ключ }));
}

export const УРОВНИ = [
    {
        id: 'три',
        имя: 'До, ре, ми',
        подпись: 'Три первые ноты',
        вопросы: набор('скрипичный', ['до', 4], ['ми', 4])
    },
    {
        id: 'пять',
        имя: 'До — соль',
        подпись: 'Пять нот подряд',
        вопросы: набор('скрипичный', ['до', 4], ['соль', 4])
    },
    {
        id: 'октава',
        имя: 'Первая октава',
        подпись: 'От до до си',
        вопросы: набор('скрипичный', ['до', 4], ['си', 4])
    },
    {
        id: 'стан',
        имя: 'Скрипичный ключ',
        подпись: 'Весь стан и добавочные',
        вопросы: набор('скрипичный', ['до', 4], ['соль', 5])
    },
    {
        id: 'бас-пять',
        имя: 'Басовый ключ',
        подпись: 'До — соль малой октавы',
        вопросы: набор('басовый', ['до', 3], ['соль', 3])
    },
    {
        id: 'бас',
        имя: 'Весь басовый ключ',
        подпись: 'От соль большой до до первой',
        вопросы: набор('басовый', ['соль', 2], ['до', 4])
    },
    {
        id: 'оба',
        имя: 'Два ключа вместе',
        подпись: 'Ключ меняется на ходу',
        вопросы: [
            ...набор('скрипичный', ['до', 4], ['соль', 5]),
            ...набор('басовый', ['соль', 2], ['до', 4])
        ]
    }
];

export function уровень(id) {
    return УРОВНИ.find((у) => у.id === id) || null;
}

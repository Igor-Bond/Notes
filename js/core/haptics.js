/**
 * Отклик вибрацией.
 *
 * Нужен там, где звук выключен, — а выключен он часто: занимаются и в
 * машине, и в коридоре музыкальной школы, и рядом со спящим младшим. Без
 * звука у нажатия остаётся только цвет, а глаза в этот момент на стане, а не
 * на кнопке.
 *
 * Вибрация не привязана к настройке звука намеренно: она и есть замена
 * звуку, а не его добавка. Её задача — подтвердить нажатие, а не наградить,
 * поэтому обе она короткая, и «мимо» отличается не силой, а рисунком.
 *
 * Поддержки может не быть вовсе (в Safari на iPhone и iPad её нет) — тогда
 * модуль молчит. Проверять поддержку снаружи не нужно: это его забота.
 */

function дрогнуть(рисунок) {
    try {
        navigator.vibrate?.(рисунок);
    } catch {
        // Вибрация запрещена настройками или невозможна на этом устройстве.
        // Занятию это безразлично, и сообщать об этом некому
    }
}

export const дрожь = {

    /** Есть ли вибрация на этом устройстве. */
    get доступна() {
        return typeof navigator !== 'undefined' && typeof navigator.vibrate === 'function';
    },

    /** Короткий толчок: ответ принят. */
    верно() {
        дрогнуть(14);
    },

    /** Два толчка через паузу: не эта нота. Не длиннее и не сильнее — иначе
     *  получается наказание, которого в тренажёре нет (Р-9). */
    мимо() {
        дрогнуть([12, 70, 12]);
    },

    /** Совсем лёгкий — на подсказку и переходы. */
    касание() {
        дрогнуть(8);
    }
};

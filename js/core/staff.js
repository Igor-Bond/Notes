/**
 * Нотный стан рисунком.
 *
 * Собирается строкой SVG, а не картинками: нота встаёт на любую линейку без
 * отдельного файла, добавочные линейки появляются сами, и всё это масштабируется
 * от телефона до телевизора без размытия. Картинок в проекте нет вовсе.
 *
 * Система координат одна на весь файл: `Y_НИЗ` — нижняя линейка стана,
 * ПОЛУШАГ — расстояние от линейки до соседнего промежутка. Положение ноты
 * приходит из notes.js в тех же полушагах, поэтому вся геометрия сводится к
 * одному умножению. Ключи нарисованы в этих же координатах — потому и
 * встают точно: скрипичный завивается вокруг линейки соль, басовый ставит
 * точки вокруг линейки фа.
 */

import { положение, добавочные, имя } from './notes.js';

const ШИРИНА = 240;
const ВЫСОТА = 200;

const ПОЛУШАГ = 10;
const Y_НИЗ = 140;

/** Куда ставится головка ноты. Левее — ключ, правее — воздух. */
const X_НОТЫ = 175;

/** Опорная нота подсказки — левее спрашиваемой: считают всегда от неё. */
const X_ОПОРЫ = 115;

const ГОЛОВКА_X = 12;
const ГОЛОВКА_Y = 9;
const ШТИЛЬ = 52;

/** Ордината положения: 0 — нижняя линейка, 8 — верхняя. */
export function y(поз) {
    return Y_НИЗ - поз * ПОЛУШАГ;
}

/**
 * Ключи нарисованы линией, а не заливкой контура.
 *
 * Настоящий нотный знак — это контур с переменной толщиной, и повторить его
 * на глаз нельзя: получится клякса, в которой ребёнок не узнает ключ. Линия
 * постоянной толщины выглядит как написанное от руки — а от руки он их и
 * будет писать.
 *
 * Готовый шрифт с нотными знаками отпадает по другой причине: юникодный
 * символ есть не в каждой системе, и там, где его нет, ребёнок получает
 * пустой прямоугольник вместо ключа. Собственный рисунок отказать не может.
 */
const КЛЮЧ_РИСУНОК = {
    скрипичный: `
        <path d="M 40 170
                 C 58 178, 68 166, 64 150
                 C 60 130, 44 120, 38 104
                 C 32 88, 40 64, 52 48
                 C 60 38, 60 28, 52 26
                 C 44 24, 38 36, 40 50
                 C 42 68, 54 84, 58 104
                 C 62 124, 58 134, 48 134
                 C 38 134, 33 125, 36 116
                 C 39 108, 50 106, 55 114"
              fill="none" stroke="currentColor" stroke-width="5"
              stroke-linecap="round" stroke-linejoin="round"/>
    `,
    басовый: `
        <path d="M 34 84
                 C 34 66, 62 62, 66 84
                 C 70 106, 52 124, 30 136"
              fill="none" stroke="currentColor" stroke-width="6"
              stroke-linecap="round" stroke-linejoin="round"/>
        <circle cx="80" cy="72" r="4.5" fill="currentColor"/>
        <circle cx="80" cy="92" r="4.5" fill="currentColor"/>
    `
};

/** Пять линеек стана. */
function линейки() {
    return [0, 2, 4, 6, 8]
        .map((поз) => `<line x1="14" y1="${y(поз)}" x2="${ШИРИНА - 14}" y2="${y(поз)}"
                             stroke="currentColor" stroke-width="2"/>`)
        .join('');
}

/**
 * Добавочные линейки чуть шире головки.
 *
 * Вровень с головкой они читаются как часть самой ноты, и до первой октавы
 * выглядит перечёркнутым овалом, а не нотой на линейке.
 */
function добавочныеЛинейки(поз) {
    return добавочные(поз)
        .map((п) => `<line x1="${X_НОТЫ - 22}" y1="${y(п)}" x2="${X_НОТЫ + 22}" y2="${y(п)}"
                           stroke="currentColor" stroke-width="2"/>`)
        .join('');
}

/**
 * Опорная нота подсказки — бледная, подписанная и без штиля.
 *
 * Без штиля нарочно: штиль сделал бы её равной спрашиваемой, а она не
 * вопрос, а точка отсчёта. Подпись стоит под станом её же цветом — иначе
 * подсказка превращается во вторую загадку.
 */
function опорнаяНота(н, ключ) {
    const поз = положение(н, ключ);
    const cy = y(поз);

    const линейки = добавочные(поз)
        .map((п) => `<line x1="${X_ОПОРЫ - 20}" y1="${y(п)}" x2="${X_ОПОРЫ + 20}" y2="${y(п)}"
                           stroke="currentColor" stroke-width="2"/>`)
        .join('');

    return `
        <g class="stan-anchor">
            ${линейки}
            <ellipse cx="${X_ОПОРЫ}" cy="${cy}" rx="${ГОЛОВКА_X}" ry="${ГОЛОВКА_Y}"
                     fill="currentColor" transform="rotate(-20 ${X_ОПОРЫ} ${cy})"/>
            <text x="${X_ОПОРЫ}" y="186" text-anchor="middle"
                  font-size="20" fill="currentColor">${имя(н)}</text>
        </g>
    `;
}

/**
 * Головка со штилем.
 *
 * Штиль вверх у нот ниже середины стана и вниз у тех, что выше, — правило
 * настоящей записи, и нарушать его в учебном тренажёре нельзя: ребёнок
 * запомнит рисунок целиком, вместе с направлением палочки.
 *
 * Наклон головки на 20 градусов — тоже не украшение: так её рисуют, и так
 * она не сливается с линейкой, на которой сидит.
 */
function нота(поз) {
    const cy = y(поз);
    const вверх = поз < 4;

    const x1 = вверх ? X_НОТЫ + ГОЛОВКА_X - 2 : X_НОТЫ - ГОЛОВКА_X + 2;
    const y2 = вверх ? cy - ШТИЛЬ : cy + ШТИЛЬ;

    return `
        <line x1="${x1}" y1="${cy}" x2="${x1}" y2="${y2}"
              stroke="currentColor" stroke-width="3" stroke-linecap="round"/>
        <ellipse cx="${X_НОТЫ}" cy="${cy}" rx="${ГОЛОВКА_X}" ry="${ГОЛОВКА_Y}"
                 fill="currentColor" transform="rotate(-20 ${X_НОТЫ} ${cy})"/>
    `;
}

/**
 * Стан с одной нотой.
 *
 * `класс` попадает на корневой svg: подсветка верного и неверного ответа
 * делается цветом через CSS, а не перерисовкой — currentColor у всех частей
 * рисунка один, и менять надо одно свойство.
 */
export function нарисовать({ нота: н, ключ, класс = '', опора = null }) {
    const поз = положение(н, ключ);

    return `
        <svg class="stan ${класс}" viewBox="0 0 ${ШИРИНА} ${ВЫСОТА}"
             role="img" aria-label="Нота на нотном стане" focusable="false">
            <g class="stan-lines">${линейки()}</g>
            <g class="stan-clef">${КЛЮЧ_РИСУНОК[ключ] || ''}</g>
            ${опора === null ? '' : опорнаяНота(опора, ключ)}
            <g class="stan-note">${добавочныеЛинейки(поз)}${нота(поз)}</g>
        </svg>
    `;
}

/** Пустой стан с ключом — для карточек уровней. */
export function нарисоватьКлюч(ключ) {
    return `
        <svg class="stan stan-mini" viewBox="0 0 110 ${ВЫСОТА}"
             role="img" aria-label="${ключ === 'басовый' ? 'Басовый ключ' : 'Скрипичный ключ'}"
             focusable="false">
            <g class="stan-lines">
                ${[0, 2, 4, 6, 8].map((поз) => `<line x1="8" y1="${y(поз)}" x2="102" y2="${y(поз)}"
                    stroke="currentColor" stroke-width="2"/>`).join('')}
            </g>
            <g class="stan-clef">${КЛЮЧ_РИСУНОК[ключ] || ''}</g>
        </svg>
    `;
}

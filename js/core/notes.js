/**
 * Ноты, ключи и их место на нотном стане.
 *
 * Нота здесь — одно целое число, сквозной номер ступени: `октава * 7 +
 * ступень`, где ступень 0 — до, 6 — си. Не частота и не MIDI-номер, потому
 * что тренажёр учит читать запись, а запись состоит из ступеней: до-диез и
 * до стоят на стане в одном месте, а фа и ми — в разных, хотя между ними
 * тот же полутон. При номере по полутонам каждое обращение к стану начиналось
 * бы с обратного перевода, и до-бемоль оказался бы на линейке си.
 *
 * Полутона нужны ровно одному — звуку, и берутся только там.
 *
 * Октавы считаются как принято в научной записи: до первой октавы — это
 * `до, 4`, средняя до фортепиано. Русские названия октав («первая»,
 * «малая») отсюда же, но только для показа человеку.
 */

export const СТУПЕНИ = ['до', 'ре', 'ми', 'фа', 'соль', 'ля', 'си'];

/** Сколько полутонов от «до» до каждой ступени. Нужно только звуку. */
const ПОЛУТОНА = [0, 2, 4, 5, 7, 9, 11];

/**
 * Русские названия октав.
 *
 * Ключ — номер октавы научной записи. Ниже контроктавы и выше четвёртой
 * тренажёру делать нечего: на стане это шесть добавочных линеек, которые и
 * взрослый считает пальцем.
 */
const ИМЕНА_ОКТАВ = {
    1: 'контроктавы',
    2: 'большой октавы',
    3: 'малой октавы',
    4: 'первой октавы',
    5: 'второй октавы',
    6: 'третьей октавы'
};

/** Сквозной номер ступени: нота('ми', 4) === 30. */
export function нота(имя, октава) {
    const ступень = СТУПЕНИ.indexOf(имя);
    if (ступень < 0) throw new Error(`Нет такой ступени: ${имя}`);

    return октава * 7 + ступень;
}

export function ступень(н) {
    return ((н % 7) + 7) % 7;
}

export function октава(н) {
    return Math.floor(н / 7);
}

export function имя(н) {
    return СТУПЕНИ[ступень(н)];
}

/** «до первой октавы» — для подсказки и для итога занятия. */
export function полноеИмя(н) {
    const где = ИМЕНА_ОКТАВ[октава(н)];
    return где ? `${имя(н)} ${где}` : имя(н);
}

/**
 * Частота в герцах — для звука.
 *
 * Строй равномерно темперированный, ля первой октавы — 440 Гц. Через
 * MIDI-номер, а не таблицей: таблица на три октавы это двадцать одно число,
 * которое надо не перепутать, а формула проверяется одной нотой.
 */
export function частота(н) {
    const midi = (октава(н) + 1) * 12 + ПОЛУТОНА[ступень(н)];
    return 440 * Math.pow(2, (midi - 69) / 12);
}

/**
 * Ключи и их опора — нота на нижней линейке стана.
 *
 * Скрипичный: ми первой октавы. Басовый: соль большой октавы. Всё положение
 * ноты на стане выводится отсюда вычитанием, поэтому больше про ключи знать
 * нечего — ни таблиц линеек, ни списков «какая нота где».
 */
export const КЛЮЧИ = {
    скрипичный: { опора: нота('ми', 4), имя: 'Скрипичный ключ' },
    басовый: { опора: нота('соль', 2), имя: 'Басовый ключ' }
};

/**
 * Положение ноты на стане в полушагах от нижней линейки.
 *
 * 0 — нижняя линейка, 1 — промежуток над ней, 8 — верхняя линейка.
 * Отрицательные значения уходят под стан, всё что больше восьми — над ним.
 * Чётные — линейки, нечётные — промежутки, и это не совпадение, а то, ради
 * чего счёт ведётся в полушагах.
 */
export function положение(н, ключ) {
    const к = КЛЮЧИ[ключ];
    if (!к) throw new Error(`Нет такого ключа: ${ключ}`);

    return н - к.опора;
}

/** Обратное: какая нота стоит в этом месте стана. */
export function нотаПоПоложению(поз, ключ) {
    return КЛЮЧИ[ключ].опора + поз;
}

/**
 * Добавочные линейки для ноты за пределами стана.
 *
 * Рисуются только те, что между станом и нотой, — и только чётные: линейка
 * есть линейка. Си малой октавы в скрипичном ключе висит под линейкой до,
 * и линеек ему нужно ровно одна, а не две: нота сидит в промежутке.
 */
export function добавочные(поз) {
    const линейки = [];

    for (let p = -2; p >= поз; p -= 2) линейки.push(p);
    for (let p = 10; p <= поз; p += 2) линейки.push(p);

    return линейки;
}

/** Все ноты от одной до другой включительно — из них набираются уровни. */
export function диапазон(от, до) {
    const ноты = [];
    for (let н = от; н <= до; н += 1) ноты.push(н);
    return ноты;
}

/**
 * Опорные ноты — якоря, от которых считают остальные.
 *
 * Это не выдумка тренажёра, а способ, которым ноты учат и без него:
 * вместо одиннадцати линеек и промежутков ребёнок запоминает три места,
 * которые узнаёт мгновенно, а всё остальное находит шагами от ближайшего.
 *
 * Выбраны те, у которых на стане есть приметы. Скрипичный: до на
 * добавочной под станом, соль — вокруг неё завивается сам ключ, фа — на
 * верхней линейке. Басовый: фа между двумя точками ключа, соль на нижней
 * линейке, до на добавочной над станом.
 */
export const ОПОРЫ = {
    скрипичный: [нота('до', 4), нота('соль', 4), нота('фа', 5)],
    басовый: [нота('соль', 2), нота('фа', 3), нота('до', 4)]
};

/**
 * Ближайшая опора и сколько до неё ступеней.
 *
 * Знак у `шагов` говорит, куда идти: плюс — наша нота выше опоры, минус —
 * ниже. Ноль означает, что нота и есть опора, и подсказке остаётся только
 * назвать её.
 */
export function опора(н, ключ) {
    const список = ОПОРЫ[ключ];
    if (!список) throw new Error(`Нет такого ключа: ${ключ}`);

    const ближайшая = список.reduce((лучшая, о) =>
        Math.abs(н - о) < Math.abs(н - лучшая) ? о : лучшая);

    return { нота: ближайшая, шагов: н - ближайшая };
}

/**
 * «две ступени» — с падежом.
 *
 * Подсказку читает ребёнок, который читает по слогам: «на 2 ступень выше»
 * он разбирать не станет, а спотыкаться на подсказке — худшее, что она
 * может сделать.
 */
export function ступенями(сколько) {
    const н = Math.abs(сколько);
    const слова = ['', 'одну ступень', 'две ступени', 'три ступени',
        'четыре ступени', 'пять ступеней', 'шесть ступеней', 'семь ступеней'];

    return слова[н] || `${н} ступеней`;
}

/** Подсказка словами: от какой опоры и в какую сторону считать. */
export function подсказка(н, ключ) {
    const { нота: о, шагов } = опора(н, ключ);

    if (шагов === 0) return `Это опорная нота — ${полноеИмя(о)}`;

    const куда = шагов > 0 ? 'выше' : 'ниже';
    return `Считай от ноты ${имя(о)}: на ${ступенями(шагов)} ${куда}`;
}

/**
 * Звук ноты.
 *
 * Синтезируется на месте, файлов со звуками в проекте нет: три десятка нот
 * это три десятка запросов и мегабайты, которые надо ещё и держать в
 * офлайне. Формула частоты живёт в notes.js, здесь только огибающая.
 *
 * Зачем звук вообще. Тренажёр учит читать запись глазами, но нота — это
 * прежде всего звук; молча показанная головка на линейке остаётся значком.
 * Услышав её, ребёнок связывает знак с тем, что поёт на занятии.
 *
 * Контекст создаётся при первом нажатии, а не при запуске: браузер не даёт
 * звучать странице, которой никто не касался, и созданный заранее контекст
 * остаётся навсегда приглушённым.
 */

import { частота } from './notes.js';

let контекст = null;

function получить() {
    if (!контекст) {
        const Ctor = globalThis.AudioContext || globalThis.webkitAudioContext;
        if (!Ctor) return null;
        контекст = new Ctor();
    }

    // Система усыпляет контекст вместе со свёрнутым приложением, и
    // проснувшаяся страница звучала бы молча до перезагрузки
    // resume отказывает там, где страницы ещё не касались, и отказ приходит
    // обещанием: без перехвата он всплывает необработанным при каждом ответе
    if (контекст.state === 'suspended') контекст.resume()?.catch(() => {});

    return контекст;
}

export const звук = {

    /** Есть ли звук в этом браузере вообще — профиль показывает настройку только тогда. */
    get доступен() {
        return !!(globalThis.AudioContext || globalThis.webkitAudioContext);
    },

    /**
     * Сыграть ноту.
     *
     * Треугольная волна, а не синус и не пила: синус на маленьком динамике
     * телефона почти не слышен, пила режет ухо. Мягкая атака и спад — щелчок
     * в начале и в конце ребёнок слышит как «сломалось».
     */
    сыграть(н, { длительность = 0.7, громкость = 0.18 } = {}) {
        const ctx = получить();
        if (!ctx) return;

        const t = ctx.currentTime;

        const осц = ctx.createOscillator();
        осц.type = 'triangle';
        осц.frequency.value = частота(н);

        const усилитель = ctx.createGain();
        усилитель.gain.setValueAtTime(0, t);
        усилитель.gain.linearRampToValueAtTime(громкость, t + 0.02);
        усилитель.gain.exponentialRampToValueAtTime(0.0001, t + длительность);

        осц.connect(усилитель).connect(ctx.destination);
        осц.start(t);
        осц.stop(t + длительность + 0.05);
    },

    /**
     * Короткий отклик на ответ: вверх — верно, вниз — мимо.
     *
     * Словами «правильно» и «неправильно» это говорить нельзя — читать
     * ребёнок ещё учится, а два интервала он различает сразу и без
     * подписи.
     */
    отклик(верно) {
        const ctx = получить();
        if (!ctx) return;

        const шаги = верно ? [784, 1046] : [392, 294];

        шаги.forEach((гц, i) => {
            const t = ctx.currentTime + i * 0.09;

            const осц = ctx.createOscillator();
            осц.type = 'triangle';
            осц.frequency.value = гц;

            const у = ctx.createGain();
            у.gain.setValueAtTime(0, t);
            у.gain.linearRampToValueAtTime(0.14, t + 0.01);
            у.gain.exponentialRampToValueAtTime(0.0001, t + 0.18);

            осц.connect(у).connect(ctx.destination);
            осц.start(t);
            осц.stop(t + 0.2);
        });
    }
};

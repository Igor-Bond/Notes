/**
 * Звук.
 *
 * Синтезируется на месте, файлов со звуками в проекте нет: три десятка нот
 * это три десятка запросов и мегабайты, которые надо ещё и держать в
 * офлайне. Формула частоты живёт в notes.js, здесь только тембр.
 *
 * Тембр собирается сложением гармоник — синусоид на кратных частотах, у
 * каждой своя громкость и свой спад. Так звучит струна: верхние призвуки
 * гаснут быстрее нижнего, и звук «темнеет», пока длится. Одна треугольная
 * волна, с которой тренажёр начинался, этого не делает — она звучит ровно и
 * пусто, как сигнал будильника, и ребёнок перестаёт её слушать.
 *
 * Зачем звук вообще. Тренажёр учит читать запись глазами, но нота — это
 * прежде всего звук; молча показанная головка на линейке остаётся значком.
 * Услышав её, ребёнок связывает знак с тем, что поёт на занятии.
 *
 * Контекст создаётся при первом нажатии, а не при запуске: браузер не даёт
 * звучать странице, которой никто не касался, и созданный заранее контекст
 * остаётся навсегда приглушённым.
 */

import { частота } from './notes.js';

let контекст = null;

function получить() {
    if (!контекст) {
        const Ctor = globalThis.AudioContext || globalThis.webkitAudioContext;
        if (!Ctor) return null;
        контекст = new Ctor();
    }

    // resume отказывает там, где страницы ещё не касались, и отказ приходит
    // обещанием: без перехвата он всплывает необработанным при каждом ответе
    if (контекст.state === 'suspended') контекст.resume()?.catch(() => {});

    return контекст;
}

/**
 * Из чего складывается нота.
 *
 * Доли подобраны на слух под маленький динамик планшета: там нижняя
 * гармоника почти не слышна, и без верхних нота превращается в глухой стук.
 * Спад — доля от общей длительности: чем выше призвук, тем короче он живёт.
 */
const ГАРМОНИКИ = [
    { кратность: 1, доля: 1.00, спад: 1.00 },
    { кратность: 2, доля: 0.42, спад: 0.70 },
    { кратность: 3, доля: 0.18, спад: 0.50 },
    { кратность: 4, доля: 0.10, спад: 0.36 },
    { кратность: 6, доля: 0.05, спад: 0.24 }
];

/**
 * Один звук заданной частоты.
 *
 * Атака в пять миллисекунд, дальше только спад — у струны нет ровной
 * середины, она гаснет с первого мгновения. Щелчок в начале и в конце
 * ребёнок слышит как поломку, поэтому обе границы сглажены.
 */
function тон(ctx, гц, когда, { длительность = 1.4, громкость = 0.22 } = {}) {
    for (const г of ГАРМОНИКИ) {
        const осц = ctx.createOscillator();
        осц.type = 'sine';
        осц.frequency.value = гц * г.кратность;

        const жизнь = длительность * г.спад;

        const у = ctx.createGain();
        у.gain.setValueAtTime(0, когда);
        у.gain.linearRampToValueAtTime(громкость * г.доля, когда + 0.005);
        у.gain.exponentialRampToValueAtTime(0.0001, когда + жизнь);

        осц.connect(у).connect(ctx.destination);
        осц.start(когда);
        осц.stop(когда + жизнь + 0.05);
    }
}

/** Несколько звуков подряд: [[частота, задержка, настройки], …]. */
function цепочка(шаги) {
    const ctx = получить();
    if (!ctx) return;

    const начало = ctx.currentTime;
    for (const [гц, задержка, настройки] of шаги) {
        тон(ctx, гц, начало + задержка, настройки);
    }
}

/* Ноты для откликов — по именам, чтобы читалось как музыка, а не как числа */
const ДО = 523.25;
const МИ = 659.25;
const СОЛЬ = 784.0;
const ДО2 = 1046.5;
const МИ2 = 1318.5;
const СОЛЬ_НИЗ = 392.0;
const МИ_НИЗ = 329.63;

export const звук = {

    /** Есть ли звук в этом браузере вообще. */
    get доступен() {
        return !!(globalThis.AudioContext || globalThis.webkitAudioContext);
    },

    /** Сыграть ноту. */
    сыграть(н, настройки = {}) {
        const ctx = получить();
        if (!ctx) return;

        тон(ctx, частота(н), ctx.currentTime, настройки);
    },

    /**
     * Короткий отклик на ответ.
     *
     * Верный — две ноты вверх, бодро и коротко. Неверный — две вниз, тише и
     * мягче: это не окрик, а «не эта». Словами говорить нельзя — читать
     * ребёнок ещё учится, а два интервала он различает сразу и без подписи.
     */
    отклик(верно) {
        if (верно) {
            цепочка([
                [СОЛЬ, 0, { длительность: 0.4, громкость: 0.2 }],
                [ДО2, 0.09, { длительность: 0.6, громкость: 0.2 }]
            ]);
        } else {
            цепочка([
                [СОЛЬ_НИЗ, 0, { длительность: 0.35, громкость: 0.13 }],
                [МИ_НИЗ, 0.11, { длительность: 0.5, громкость: 0.13 }]
            ]);
        }
    },

    /**
     * Искра за несколько верных подряд.
     *
     * Высокая и очень короткая: она приходит поверх обычного отклика и не
     * должна его перекрывать — это блёстка, а не вторая награда.
     */
    искра() {
        цепочка([
            [ДО2, 0.22, { длительность: 0.25, громкость: 0.1 }],
            [МИ2, 0.30, { длительность: 0.3, громкость: 0.1 }]
        ]);
    },

    /**
     * Фанфара за занятие без ошибок.
     *
     * Трезвучие вверх и верхнее до — то самое «получилось», что играют на
     * занятии. Только за три звезды: фанфара на каждом итоге за неделю
     * превращается в звук, который выключают вместе со всем остальным.
     */
    фанфара() {
        цепочка([
            [ДО, 0, { длительность: 0.5 }],
            [МИ, 0.12, { длительность: 0.5 }],
            [СОЛЬ, 0.24, { длительность: 0.6 }],
            [ДО2, 0.36, { длительность: 1.4, громкость: 0.24 }],
            [МИ, 0.36, { длительность: 1.4, громкость: 0.10 }]
        ]);
    }
};

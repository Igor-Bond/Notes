/**
 * Что уже пройдено — в localStorage.
 *
 * Не IndexedDB: всё хранилище тренажёра это семь строчек про уровни, и база
 * с версиями схемы здесь была бы дороже задачи. Синхронизации между
 * устройствами тоже нет намеренно — тренажёр стоит на одном планшете, а
 * учётная запись ребёнку не нужна.
 *
 * Отказ хранилища не должен ронять занятие. В приватном окне localStorage
 * бросает исключение на любом обращении, и тренажёр в этом случае работает
 * как работал — просто забывает результаты при закрытии.
 */

/**
 * Ключ хранения.
 *
 * Подменяется проверками: они гоняют настоящее хранилище — иначе проверять
 * нечего, — и без подмены стёрли бы звёзды ребёнка на том же устройстве.
 */
const КЛЮЧ = globalThis.__NOTY_KEY__ || 'noty.v1';

const ПУСТО = { уровни: {}, звук: true };

/** Запасная память: когда хранилище недоступно, занятие всё равно идёт. */
let вПамяти = null;

function прочитатьСырое() {
    try {
        const текст = localStorage.getItem(КЛЮЧ);
        if (!текст) return null;
        return JSON.parse(текст);
    } catch {
        return null;
    }
}

/**
 * Чужое или испорченное содержимое не должно ломать запуск.
 *
 * Ключ в localStorage может пережить смену версии, а может оказаться и
 * вовсе чужим — адрес один на все страницы домена. Поэтому не доверяем
 * ничему: всё, что не похоже на своё, заменяется пустым.
 */
function привести(данные) {
    if (!данные || typeof данные !== 'object') return { ...ПУСТО, уровни: {} };

    const уровни = {};

    for (const [id, з] of Object.entries(данные.уровни || {})) {
        if (!з || typeof з !== 'object') continue;

        уровни[id] = {
            занятий: Number(з.занятий) || 0,
            звёзды: Math.min(3, Math.max(0, Number(з.звёзды) || 0)),
            лучший: Math.max(0, Number(з.лучший) || 0),
            когда: Number(з.когда) || 0
        };
    }

    return { уровни, звук: данные.звук !== false };
}

function прочитать() {
    if (вПамяти) return вПамяти;
    return привести(прочитатьСырое());
}

function записать(данные) {
    try {
        localStorage.setItem(КЛЮЧ, JSON.stringify(данные));
        вПамяти = null;
    } catch {
        вПамяти = данные;
    }

    return данные;
}

export const хранилище = {

    всё() {
        return прочитать();
    },

    уровень(id) {
        return прочитать().уровни[id] || { занятий: 0, звёзды: 0, лучший: 0, когда: 0 };
    },

    /**
     * Итог занятия.
     *
     * Звёзды и лучший результат только растут: уровень, взятый на три
     * звезды, не должен терять их из-за того, что ребёнок открыл его
     * поиграть и отвлёкся. Снятая звезда читается как наказание за то, что
     * он вернулся, — и он перестаёт возвращаться.
     */
    записатьЗанятие(id, итог) {
        const данные = прочитать();
        const было = данные.уровни[id] || { занятий: 0, звёзды: 0, лучший: 0, когда: 0 };

        данные.уровни[id] = {
            занятий: было.занятий + 1,
            звёзды: Math.max(было.звёзды, итог.звёзды),
            лучший: Math.max(было.лучший, итог.верных),
            когда: Date.now()
        };

        записать(данные);
        return данные.уровни[id];
    },

    get звук() {
        return прочитать().звук;
    },

    set звук(включён) {
        const данные = прочитать();
        данные.звук = !!включён;
        записать(данные);
    },

    сбросить() {
        записать({ уровни: {}, звук: прочитать().звук });
    }
};

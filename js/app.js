/**
 * Экраны и маршрутизация.
 *
 * Маршрут живёт в адресной строке после решётки: #/занятие/октава. Так
 * работает кнопка «назад» браузера — на планшете ребёнок жмёт её первой, —
 * и так приложение остаётся набором статических файлов: серверных правил
 * переписывания путей на GitHub Pages нет.
 */

import { home } from './modules/home.js';
import { занятиеЭкран } from './modules/drill.js';
import { итогЭкран } from './modules/result.js';

/**
 * Список экранов собирается при первом обращении, а не при загрузке модуля.
 *
 * Здесь круговая зависимость: app.js импортирует экраны, а каждый экран
 * импортирует app.js ради перехода и перерисовки. Модули ES такое допускают,
 * но пока модуль не доисполнен, его переменные недоступны, и сборка списка
 * прямо в теле файла падает, стоит проверке импортировать экран первым.
 */
let ЭКРАНЫ = null;

function экраны() {
    if (!ЭКРАНЫ) {
        ЭКРАНЫ = {
            выбор: home,
            занятие: занятиеЭкран,
            итог: итогЭкран
        };
    }

    return ЭКРАНЫ;
}

const ПО_УМОЛЧАНИЮ = 'выбор';

function разобрать(hash) {
    const части = String(hash || '').replace(/^#\/?/, '').split('/').filter(Boolean);
    const имя = decodeURIComponent(части[0] || ПО_УМОЛЧАНИЮ);

    return {
        name: экраны()[имя] ? имя : ПО_УМОЛЧАНИЮ,
        param: части[1] ? decodeURIComponent(части[1]) : null
    };
}

export const app = {

    route: { name: ПО_УМОЛЧАНИЮ, param: null },

    init() {
        /*
         * Кнопка «назад» браузера и адрес, введённый руками.
         *
         * Переходы внутри приложения рисуют сами (см. go), поэтому событие
         * от собственного же перехода приходит на уже нарисованный экран —
         * и повторная отрисовка здесь была бы не просто лишней: экран
         * занятия собрался бы заново и начал занятие с первого вопроса.
         */
        window.addEventListener('hashchange', () => {
            const маршрут = разобрать(location.hash);
            if (маршрут.name === app.route.name && маршрут.param === app.route.param) return;

            app.route = маршрут;
            app.render();
        });

        app.route = разобрать(location.hash);
        app.render();
    },

    /**
     * Переход: рисует сразу, адрес правит следом.
     *
     * Сначала отрисовка полагалась на событие hashchange, и это давало две
     * поломки разом. Переход на тот же адрес события не вызывает вовсе —
     * «Ещё раз» на том же уровне не начинал нового занятия. А когда адрес
     * всё-таки менялся, между вызовом go и отрисовкой оставался промежуток,
     * в котором любое нажатие рисовало ещё прежний маршрут: экран занятия
     * видел чужой уровень в параметре и начинал занятие заново.
     *
     * Теперь отрисовка происходит здесь же, а адрес меняется ради кнопки
     * «назад» и перезагрузки. Имя экрана кодируется наравне с параметром:
     * браузер хранит хвост адреса закодированным, и несравнимые строки
     * означали бы лишнюю запись в истории на каждом переходе.
     */
    go(имя, параметр) {
        const адрес = параметр
            ? `#/${encodeURIComponent(имя)}/${encodeURIComponent(параметр)}`
            : `#/${encodeURIComponent(имя)}`;

        app.route = разобрать(адрес);
        app.render();

        if (location.hash !== адрес) location.hash = адрес;
    },

    render() {
        const место = document.getElementById('screen');
        if (!место) return;

        const экран = экраны()[app.route.name] || home;

        try {
            место.innerHTML = String(экран.render(app.route.param));
            место.scrollTop = 0;
        } catch (e) {
            console.error('[Экран] Не удалось нарисовать:', e);
            место.innerHTML = '<div class="empty-note">Экран не открылся. Попробуйте обновить страницу.</div>';
        }

        экран.after?.(app.route.param);
    }
};

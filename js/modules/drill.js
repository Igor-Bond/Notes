/**
 * Экран занятия: нота на стане и ряд кнопок.
 *
 * Занятие держится в переменной модуля, а не в адресе: в адресе только
 * уровень. Поэтому обновление страницы посреди занятия начинает его заново —
 * и это правильнее, чем восстанавливать наполовину отвеченное: ребёнок,
 * вернувшийся через час, не помнит, на каком он был вопросе.
 *
 * Верный ответ уходит сам через мгновение, неверный ждёт нажатия «Дальше».
 * Разница намеренная: на верном смотреть не на что, а неверный ради того и
 * случился, чтобы на правильное имя посмотреть.
 */

import { ui } from '../core/ui.js';
import { actions } from '../core/actions.js';
import { уровень } from '../core/levels.js';
import { занятие, кнопки, изОшибок } from '../core/drill.js';
import { нарисовать } from '../core/staff.js';
import { полноеИмя, имя, СТУПЕНИ } from '../core/notes.js';
import { звук } from '../core/tone.js';
import { хранилище } from '../core/store.js';
import { app } from '../app.js';

/** Через сколько уходит верный ответ. Меньше — не успевает обрадовать. */
const ПАУЗА = 800;

let текущее = null;     // { id, имя, набор, игра }
let последний = null;   // итог законченного занятия — его читает экран итога
let таймер = 0;

/** Итог последнего занятия. Экран итога без него показывает пустоту. */
export function итогПоследнего() {
    return последний;
}

function снятьТаймер() {
    clearTimeout(таймер);
    таймер = 0;
}

/** Начать уровень с нуля. */
export function начать(id) {
    const у = уровень(id);
    if (!у) return app.go('выбор');

    снятьТаймер();
    текущее = { id, имя: у.имя, набор: у.вопросы, игра: занятие(у.вопросы) };

    app.go('занятие', id);
}

/**
 * Работа над ошибками — занятие из тех нот, на которых споткнулись.
 *
 * Результат пишется в тот же уровень: это его ноты, и лишняя строка в
 * прогрессе про «повторение уровня X» ребёнку ничего не говорит.
 */
export function повторитьОшибки(id, ошибки) {
    const набор = изОшибок(ошибки);
    if (!набор.length) return начать(id);

    снятьТаймер();
    текущее = {
        id,
        имя: уровень(id)?.имя || '',
        набор,
        игра: занятие(набор, { длина: Math.max(4, набор.length) })
    };

    app.go('занятие', id);
}

/**
 * Точки пройденного.
 *
 * Синяя точка стоит на вопросе, который сейчас на экране, а не на
 * следующем. Разница видна в паузе после ответа: пока ребёнок смотрит на
 * разобранную ошибку, синяя точка не должна уже уехать вперёд — он ещё
 * здесь.
 */
function точки(игра) {
    const история = игра.история;
    const текущий = игра.номер - 1;

    return ui.raw(Array.from({ length: игра.длина }, (_, i) => {
        let класс = '';
        if (i < история.length) класс = история[i] ? 'ok' : 'bad';
        else if (i === текущий) класс = 'now';

        return `<span class="dot ${класс}"></span>`;
    }).join(''));
}

function клавиши(игра) {
    const ответ = игра.ответ;
    const верное = ответ ? имя(ответ.вопрос.нота) : null;

    return кнопки(текущее.набор).map((ступень) => {
        const цифра = СТУПЕНИ.indexOf(ступень) + 1;

        let класс = '';
        if (ответ && ступень === верное) класс = 'ok';
        else if (ответ && ступень === ответ.дан) класс = 'bad';

        return ui.html`
            <button class="key ${класс}" data-action="ответ"
                    data-note="${ступень}" data-key="${цифра}"
                    ${ответ ? 'disabled' : ''}>
                ${ступень}<span class="key-num">${цифра}</span>
            </button>
        `;
    });
}

function приговор(игра) {
    const ответ = игра.ответ;
    if (!ответ) return ui.html`<p class="verdict hint">Какая это нота?</p>`;

    if (ответ.верно) {
        return ui.html`<p class="verdict ok">Верно — ${полноеИмя(ответ.вопрос.нота)}</p>`;
    }

    return ui.html`
        <p class="verdict bad">Это ${полноеИмя(ответ.вопрос.нота)}, а не ${ответ.дан}</p>
        <button class="next-btn" data-action="дальше" data-key="enter"> Дальше </button>
    `;
}

export const занятиеЭкран = {

    render(param) {
        // Прямая ссылка, обновление страницы, возврат «назад» — во всех этих
        // случаях занятия в памяти нет, и его надо просто начать
        if (!текущее || (param && текущее.id !== param)) {
            const у = уровень(param);
            if (!у) { app.go('выбор'); return ''; }

            текущее = { id: param, имя: у.имя, набор: у.вопросы, игра: занятие(у.вопросы) };
        }

        const игра = текущее.игра;
        const вопрос = игра.вопрос;
        if (!вопрос) { app.go('выбор'); return ''; }

        const подсветка = игра.ответ ? (игра.ответ.верно ? 'ok' : 'bad') : '';

        return ui.html`
            <div class="drill">
                <div class="drill-head">
                    <button class="icon-btn" data-action="выйти" aria-label="К уровням">←</button>
                    <div class="dots">${точки(игра)}</div>
                    <div class="count">${игра.номер} / ${игра.длина}</div>
                </div>

                <div class="stage">
                    ${ui.raw(нарисовать({ нота: вопрос.нота, ключ: вопрос.ключ, класс: подсветка }))}
                </div>

                <div class="verdict-box">${приговор(игра)}</div>

                <div class="keys">${клавиши(игра)}</div>
            </div>
        `;
    }
};

// ================== ДЕЙСТВИЯ ==================

actions.on('ответ', (el) => {
    const игра = текущее?.игра;
    if (!игра || игра.ждётШага) return;

    const ответ = игра.ответить(el.dataset.note);
    if (!ответ) return;

    if (хранилище.звук) {
        звук.отклик(ответ.верно);
        // Названная нота звучит после отклика: сначала «верно», потом сама
        // нота — иначе два звука сливаются в один непонятный
        setTimeout(() => звук.сыграть(ответ.вопрос.нота), 260);
    }

    app.render();

    // Верный ответ уходит сам, неверный остаётся до нажатия
    if (ответ.верно) {
        снятьТаймер();
        таймер = setTimeout(шаг, ПАУЗА);
    }
});

actions.on('дальше', шаг);

actions.on('выйти', () => {
    снятьТаймер();
    текущее = null;
    app.go('выбор');
});

/**
 * Шаг к следующему вопросу, а с последнего — на итог.
 *
 * Итог пишется здесь, а не на экране итога: экран может быть открыт
 * повторно кнопкой «назад», и занятие засчиталось бы дважды.
 */
function шаг() {
    снятьТаймер();

    const игра = текущее?.игра;
    if (!игра) return app.go('выбор');

    if (игра.дальше()) return app.render();

    последний = { ...игра.итог(), id: текущее.id, имя: текущее.имя };
    хранилище.записатьЗанятие(текущее.id, последний);

    текущее = null;
    app.go('итог');
}

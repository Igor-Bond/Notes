/**
 * Итог занятия.
 *
 * Показывает три вещи и ничего сверх: сколько звёзд, сколько верных и какие
 * ноты не узнались. Проценты, время и средние — взрослая радость; ребёнку
 * нужен ответ на «получилось или нет» и возможность тут же попробовать
 * снова.
 *
 * Ошибки показаны нотами, а не списком названий: «ты перепутал фа и ми»
 * ничего не объясняет, пока не видно, где эта фа стояла.
 */

import { ui } from '../core/ui.js';
import { actions } from '../core/actions.js';
import { нарисовать } from '../core/staff.js';
import { полноеИмя, нота } from '../core/notes.js';
import { звук } from '../core/tone.js';
import { хранилище } from '../core/store.js';
import { app } from '../app.js';
import { итогПоследнего, начать, повторитьОшибки } from './drill.js';

/**
 * Похвала по числу звёзд.
 *
 * Без «неудовлетворительно» и «попробуй ещё раз получше»: тренажёр, который
 * оценивает, ребёнок закрывает. Нижняя строка говорит про ноты, а не про
 * него.
 */
const СЛОВА = {
    3: 'Всё верно!',
    2: 'Почти всё!',
    1: 'Уже неплохо',
    0: 'Эти ноты ещё новые'
};

function ошибка(о) {
    return ui.html`
        <div class="miss">
            ${ui.raw(нарисовать({ нота: о.нота, ключ: о.ключ }))}
            <div class="miss-text">
                <span class="miss-right">${полноеИмя(о.нота)}</span>
                <span class="miss-wrong">ответ: ${о.дан}</span>
            </div>
        </div>
    `;
}

export const итогЭкран = {

    render() {
        const итог = итогПоследнего();

        // Прямая ссылка или возврат «назад» после перезагрузки: показывать
        // нечего, и придумывать нечего тоже
        if (!итог) { app.go('выбор'); return ''; }

        return ui.html`
            <div class="result">
                <div class="result-stars">${ui.звёзды(итог.звёзды)}</div>
                <p class="result-word">${СЛОВА[итог.звёзды]}</p>
                <p class="result-score">${итог.верных} из ${итог.всего}</p>
                <p class="result-level">${итог.имя}</p>

                ${итог.ошибки.length ? ui.html`
                    <h2 class="result-head">Эти не узнались</h2>
                    <div class="misses">${итог.ошибки.map(ошибка)}</div>
                ` : ''}

                <div class="result-buttons">
                    ${итог.ошибки.length ? ui.html`
                        <button class="big-btn" data-action="повторить-ошибки">Повторить эти ноты</button>
                    ` : ''}
                    <button class="big-btn" data-action="ещё-раз">Ещё раз</button>
                    <button class="quiet-btn" data-action="к-уровням">К уровням</button>
                </div>
            </div>
        `;
    },

    /**
     * Звёзды объявляются звуком, а не только рисунком.
     *
     * Ребёнок в этот момент смотрит на стан, а не на верх экрана, и молча
     * появившиеся звёзды пропускает. Только за безошибочное занятие: звук на
     * каждом итоге превращается в шум, который выключают вместе со звуком
     * нот.
     */
    after() {
        const итог = итогПоследнего();
        if (!итог || итог.звёзды < 3 || !хранилище.звук) return;

        // Трезвучие до-ми-соль вверх — тот же «получилось», что играют на
        // занятии
        [нота('до', 4), нота('ми', 4), нота('соль', 4)].forEach((н, i) => {
            setTimeout(() => звук.сыграть(н, { длительность: 0.5 }), i * 140);
        });
    }
};

actions.on('ещё-раз', () => начать(итогПоследнего()?.id));

actions.on('повторить-ошибки', () => {
    const итог = итогПоследнего();
    if (итог) повторитьОшибки(итог.id, итог.ошибки);
});

actions.on('к-уровням', () => app.go('выбор'));
